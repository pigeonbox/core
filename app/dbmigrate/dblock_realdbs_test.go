package dbmigrate

// core#169 / core#191：DB 级互斥闸（repo/db.DLock）在**真 PG / 真 MySQL**上的
// 跨副本验收。
//
// # 为什么必须有真库
//
// sqlite 测试形态下 DLock 走进程内条纹互斥——测不出「两个副本」；MySQL 的
// GET_LOCK 与 PG 的 pg_advisory_lock 是**会话级**锁，只有两个独立连接池
// （=两个副本、两个会话）并发才验得出互斥语义真不真。
//
// # 判据
//
//  1. 走丢更新探测器：两个副本并发跑「读计数 → 磨蹭 → 写 +1」临界段——
//     无闸形态下双方读到同一值，最终计数必丢更新；有闸形态串行化，最终
//     计数 = 总迭代数。本探测同时是 #191 的「进程锁被移除时用例仍然绿」
//     证据：临界段只依赖 DLock，没有任何进程锁参与。
//  2. 配额闸竞速（#169 issue 判据）：quota=100、10 个并发各 20，判定+插入
//     在闸段事务内 ⇒ 落库合计 ≤ 100（无闸形态=200）。
//
// # 怎么跑
//
// 默认跳过（本地没真库也会绿）；CI 的 docker 验收步（ci.yml test job）会设
// PB_TEST_PG_DSN / PB_TEST_MYSQL_DSN 并以 -run 'TestPG|TestMySQL' 跑到本文件。

import (
	"context"
	"fmt"
	"os"
	"sync"
	"testing"
	"time"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
	"gorm.io/driver/mysql"
	"gorm.io/driver/postgres"
	"gorm.io/gorm"
	"gorm.io/gorm/logger"

	"github.com/pigeonbox/core/internal/dblock"
)

// openPGPool 独立 PG 连接池（=一个副本）。
func openPGPool(dsn string) (*gorm.DB, error) {
	return gorm.Open(postgres.Open(dsn), &gorm.Config{Logger: logger.Default.LogMode(logger.Silent)})
}

// openMySQLPool 独立 MySQL 连接池（=一个副本）。
func openMySQLPool(dsn string) (*gorm.DB, error) {
	return gorm.Open(mysql.Open(dsn), &gorm.Config{Logger: logger.Default.LogMode(logger.Silent)})
}

// pgPools 未设 DSN ⇒ skip（同 pg_test.go 的既有纪律：CI 会设）。
func pgPools(t *testing.T, n int) []*gorm.DB {
	t.Helper()
	dsn := os.Getenv(pgDSNEnv)
	if dsn == "" {
		t.Skipf("未设 %s ⇒ 跳过真 PG 验收（CI 的 docker 验收步会设）", pgDSNEnv)
	}
	return openReplicaPools(t, dsn, openPGPool, n)
}

func mysqlPools(t *testing.T, n int) []*gorm.DB {
	t.Helper()
	dsn := os.Getenv(mysqlDSNEnv)
	if dsn == "" {
		t.Skipf("未设 %s ⇒ 跳过真 MySQL 验收（CI 的 docker 验收步会设）", mysqlDSNEnv)
	}
	return openReplicaPools(t, dsn, openMySQLPool, n)
}

// openReplicaPools 开 n 个**独立连接池**（=n 个副本；同一 DSN，各自会话）。
func openReplicaPools(t *testing.T, dsn string, open func(string) (*gorm.DB, error), n int) []*gorm.DB {
	t.Helper()
	pools := make([]*gorm.DB, 0, n)
	for range n {
		g, err := open(dsn)
		require.NoError(t, err)
		pools = append(pools, g)
	}
	t.Cleanup(func() {
		for _, g := range pools {
			if sqlDB, err := g.DB(); err == nil {
				_ = sqlDB.Close()
			}
		}
	})
	return pools
}

// gateProbeInit 建/清走丢更新探针表（两方言通用 SQL）。
func gateProbeInit(t *testing.T, g *gorm.DB) {
	t.Helper()
	require.NoError(t, g.Exec(`DROP TABLE IF EXISTS core_dlock_probe`).Error)
	require.NoError(t, g.Exec(`CREATE TABLE core_dlock_probe (id int PRIMARY KEY, v bigint NOT NULL)`).Error)
	require.NoError(t, g.Exec(`INSERT INTO core_dlock_probe (id, v) VALUES (1, 0)`).Error)
}

// gateLostUpdate 走丢更新探测器：每个副本跑 iters 轮「读 → 磨蹭 → 写 +1」，
// 全程只依赖 DLock（无任何进程锁）。返回落账总数。
func gateLostUpdate(t *testing.T, pools []*gorm.DB, key string, iters int) int64 {
	t.Helper()
	var wg sync.WaitGroup
	for _, g := range pools {
		for range iters {
			wg.Add(1)
			go func(g *gorm.DB) {
				defer wg.Done()
				ctx := context.Background()
				lock := dblock.NewDLock(g)
				release, err := lock.Lock(ctx, key)
				require.NoError(t, err, "取闸必须成功（等待上限 2 分钟）")
				defer release()

				var v int64
				require.NoError(t, g.Raw(`SELECT v FROM core_dlock_probe WHERE id = 1`).Scan(&v).Error)
				time.Sleep(20 * time.Millisecond) // 闸不互斥 ⇒ 后写覆盖前写（丢更新）
				require.NoError(t, g.Exec(`UPDATE core_dlock_probe SET v = ? WHERE id = 1`, v+1).Error)
			}(g)
		}
	}
	wg.Wait()

	var final int64
	require.NoError(t, pools[0].Raw(`SELECT v FROM core_dlock_probe WHERE id = 1`).Scan(&final).Error)
	return final
}

// TestPGDLockMutualExclusion 真 PG：两个副本并发临界段不丢更新（负对照：
// 无闸形态下 10 轮读改写至少丢一次，终值 ≤ 9）。
func TestPGDLockMutualExclusion(t *testing.T) {
	pools := pgPools(t, 2)
	gateProbeInit(t, pools[0])

	final := gateLostUpdate(t, pools, dblock.UploadCompletionKey("probe-pg"), 5)
	assert.EqualValues(t, 10, final,
		"两个副本各 5 轮读改写必须全部落账——跨副本互斥不成立即本用例红")
}

