// Package federation 实现 PigeonBox 的 P2P 联邦面（跨实例口令路由 + 邀请交接）。
//
// # 三个角色与构造条件（2026-10-22 命名统一）
//
// 本包导出三个服务，**构造条件不同**，这是设计使然、不是遗漏：
//
//	Node          本机节点运行时：节点身份（ed25519）、注册中心心跳、分享公告。
//	              仅在 federation.enabled 时构造；配置不合法时 bootstrap 降级
//	              为非联邦模式（单站功能不受影响）。
//	PeerDirectory 在线名录：列出联邦内可发现的对端。**无条件构造**——联邦关闭时
//	              名录仍要能读出「为什么不可用」，且注册中心地址来自配置而非运行态。
//	InviteMailbox  邀请信箱：待收邀请的出箱/留痕。**无条件构造**——收件箱在联邦
//	              关闭时也必须可用（邀请可以先到、联邦后开）。
//
// # 与设备直传的关系
//
// 2026-10-22 Wave B' 起，Box 侧**不再编排设备直传**（原 p2px 域已整包删除），
// 直传本体归独立应用 PigeonBeam。本包只保留联邦面（口令路由 + 邀请信封交接）。
