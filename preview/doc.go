// 视频/音频预览依赖外部 ffmpeg/ffprobe，经 exec.CommandContext 起子进程。
// ctx 到期（超时/取消）时，Go 的标准库行为是**只杀直接子进程**，不会遍历
// 进程树 ⇒
//
//	接入的转码驱动必须满足：**不得把真实工作进程守护化（detach 到后台）**。
