// 包装器脚本型驱动若 fork 出后台孙进程，ctx 取消只管得到包装器本身，孙进程
// 会变成孤儿继续跑：CPU 与文件句柄泄漏，且它仍能继续往预览输出目录写文件
// （预览目录与调用方 ctx 生命周期脱钩）。
//
// 为什么这里是「声明约束」而不是「就地实现整树终止」：进程树终止原语（unix：
// Setpgid 建组 → 组内 TERM → 宽限 SIGKILL；windows：Job Object 整树终止）已按
// oekit/pkg#284 提给上游收编，core 不另起一份手搓实现——同一套语义两处维护，
// 上游落地后还要迁移一次，且手搓版必然只覆盖单平台。原语落地后本包直接调用，
// 本段约束随之删除。
